export function getRoleConfig(role: InternalRole) {
  return INTERNAL_ROLES.find(r => r.role === role) || INTERNAL_ROLES[0];
}

export function hasPermission(employee: InternalEmployee | null, requiredPermission: string): boolean {
  if (!employee) return false;
  if (employee.permissions.includes('all')) return true;
  return employee.permissions.includes(requiredPermission);
}
